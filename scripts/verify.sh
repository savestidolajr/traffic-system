#!/usr/bin/env bash
# verify.sh — local mirror of the CI gate set (azure-pipelines.yml).
#
# Purpose: make "green locally" mean exactly what CI means. The 2026-07-17 red
# master (build 2496/2497) happened because a commit was verified with tsc +
# build + vitest but NOT with lint / backend-E2E / perf — the three CI-only
# gates it broke.
#
# The invariant that incident bought us:
#
#     NO GATE WHOSE INPUTS CHANGED MAY BE SKIPPED.
#
# Note what that does *not* say: it does not say every gate must run every
# time. Until 2026-07-27 this script enforced the invariant the blunt way — run
# everything, always, serially — which made the honest gate so slow that the
# temptation was to skip it entirely. That is a worse failure mode than the one
# it was guarding against.
#
# Two changes restore the invariant cheaply:
#
#   1. SCOPE.    Gates are selected from the paths actually being pushed. A
#                docs-only push does not build .NET. A web-only push does not
#                run the backend suite. Anything unrecognised escalates to the
#                full set, so the invariant holds by construction (see
#                classify_path — the default branch is "run everything").
#   2. LANES.    The selected gates run concurrently in independent lanes.
#                CI already does this (Build & Test runs Backend / Bicep /
#                Secret scan / dependency scan as parallel jobs, with Frontend
#                in Package); only this local mirror serialised them. Lanes
#                never share a build directory: the backend chain is serial
#                within itself (dotnet build -> test --no-build -> E2E all
#                touch bin/obj) and so is the web chain (tsc -b shares
#                .tsbuildinfo), but backend, web, eslint, bicep and gitleaks
#                have zero shared state.
#
# Wall time becomes max(lane) instead of sum(phases), over a subset instead of
# the whole set.
#
#   scripts/verify.sh            # scoped : every gate, restricted to what changed
#   scripts/verify.sh --quick    # scoped, fast subset (no E2E / perf / Slow trait)
#   scripts/verify.sh --full     # everything, unscoped — exact CI mirror
#   scripts/verify.sh --explain  # print the gate selection and exit
#   scripts/verify.sh --help
#
# Env:
#   VERIFY_CONFIG=Debug   build/test configuration (default Release, matching CI)
#   VERIFY_RANGE=A..B     git range to scope from (the pre-push hook sets this)
#   VERIFY_SCOPE=all      disable scoping; run every area
set -uo pipefail

# DO NOT EDIT THIS FILE WHILE IT IS RUNNING. Bash reads a script lazily by byte
# offset, so inserting lines shifts the bytes under the live interpreter and it
# resumes mid-token: you get a baffling "syntax error near unexpected token"
# naming a line that is perfectly valid on disk, and the run (and any push
# gated on it) dies. This bit twice on 2026-07-27 — once from an agent
# rewriting the script, once from a human annotating it mid-run.
#
# Wrapping the body in a brace group was tried and REJECTED: bash parses the
# compound, executes it, then keeps reading from the same stale offset, so the
# guard does not help and actually turns a survivable edit into a failure
# (measured). A snapshot re-exec would work but leaks a temp file per run.
# Not worth it — just don't edit a gate while it is gating.

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO_ROOT"

MODE="scoped"
EXPLAIN_ONLY=0

case "${1:-}" in
    -h|--help)
        cat <<'EOF'
usage: scripts/verify.sh [--quick|--full|--scoped|--explain|--help]

  (no args) / --scoped  Every gate, restricted to the areas your changes touch.
                        Unrecognised paths escalate to every area.
  --quick               As above, minus the slow tail (backend E2E, web E2E, web perf,
                        Slow-trait backend tests).
  --full                Every gate, every area, no scoping — the exact CI
                        mirror. Run before a large or cross-cutting push.
  --explain             Print the gate selection for the current change set
                        and exit without running anything.

Env:
  VERIFY_CONFIG=Debug   build/test configuration (default Release, matching CI)
  VERIFY_RANGE=A..B     git range to scope from (the pre-push hook sets this)
  VERIFY_SCOPE=all      disable scoping; run every area
EOF
        exit 0
        ;;
    --explain) EXPLAIN_ONLY=1 ;;
    "") ;;
    *)
        MODE="${1#--}"
        if [[ "$MODE" != "quick" && "$MODE" != "full" && "$MODE" != "scoped" ]]; then
            echo "usage: scripts/verify.sh [--quick|--full|--scoped|--explain|--help]" >&2
            exit 2
        fi
        ;;
esac

CONFIG="${VERIFY_CONFIG:-Release}"

# `full` is the unscoped CI mirror; `quick` drops the slow tail. Both otherwise
# obey scoping, so `--quick` on a docs change is near-instant.
if [[ "$MODE" == "full" ]]; then
    SLOW_TAIL=1
    UNIT_FILTER="Category!=Integration&Category!=E2E"
elif [[ "$MODE" == "quick" ]]; then
    SLOW_TAIL=0
    UNIT_FILTER="Category!=Integration&Category!=E2E&Category!=Slow"
else
    SLOW_TAIL=1
    UNIT_FILTER="Category!=Integration&Category!=E2E"
fi

# ── Scope ───────────────────────────────────────────────────────────────────
# Everything being pushed: committed-but-unpushed changes plus the working
# tree. Untracked files count — AzureFilesDropFileWriter.cs sat untracked for
# three days, and an untracked source file is exactly the kind of thing a
# path-scoped gate must not miss.
changed_paths() {
    if [[ -n "${VERIFY_RANGE:-}" ]]; then
        git diff --name-only "${VERIFY_RANGE}" 2>/dev/null
    else
        local upstream
        upstream="$(git rev-parse --abbrev-ref --symbolic-full-name '@{upstream}' 2>/dev/null)"
        if [[ -n "$upstream" ]]; then
            git diff --name-only "${upstream}...HEAD" 2>/dev/null
        else
            # No upstream to diff against: cannot bound the push, so escalate.
            echo "__UNKNOWN__"
        fi
    fi
    git diff --name-only HEAD 2>/dev/null
    git ls-files --others --exclude-standard
}

# Maps a path to the gate area it feeds, assigning to CLASS rather than
# echoing: this runs once per changed path, and `$(classify_path …)` forks a
# subshell each time. The working tree carries ~28k untracked files (the
# presentation footage alone is 26k), which made the fork-per-path version take
# 38 seconds to decide it had nothing to do.
#
# The default branch is deliberately "all": an unrecognised path escalates to
# the full gate set rather than silently selecting nothing. Adding a new
# top-level directory therefore fails safe (slow) instead of unsafe (skipped).
classify_path() {
    case "$1" in
        src/*|test/*|*.slnx|Directory.*.props|NuGet.config|global.json|appsettings*|scripts/e2e-backend.sh)
            CLASS=backend ;;
        web/*)
            CLASS=web ;;
        deployment/*)
            CLASS=bicep ;;
        docs/*|docs-site/*|.agents/*|architecture/*|*.md|llms.txt|scripts/docs.py|scripts/build-docs-site.py|scripts/docs-audience.py)
            CLASS=docs ;;
        .omp/*|tools/*|output/*|.github/*|.gitleaks.toml|azure-pipelines.yml|scripts/*)
            CLASS=inert ;;
        *)
            CLASS=all ;;
    esac
}

want_backend=0; want_web=0; want_bicep=0; want_secrets=0; want_docs=0
SCOPE_NOTE=""

if [[ "$MODE" == "full" || "${VERIFY_SCOPE:-}" == "all" ]]; then
    want_backend=1; want_web=1; want_bicep=1; want_secrets=1; want_docs=1
    SCOPE_NOTE="unscoped (every area)"
else
    # Collapse to the first two path components before classifying. Every rule
    # above discriminates on at most two components (`scripts/e2e-backend.sh`
    # is the longest), so this is lossless for classification while turning
    # ~28k paths into a few dozen distinct keys.
    mapfile -t _paths < <(changed_paths | command grep -v '^$' | cut -d/ -f1-2 | sort -u)
    if [[ ${#_paths[@]} -eq 0 ]]; then
        SCOPE_NOTE="no changes detected — nothing to verify"
    else
        for p in "${_paths[@]}"; do
            classify_path "$p"
            case "$CLASS" in
                backend) want_backend=1 ;;
                web)     want_web=1 ;;
                bicep)   want_bicep=1 ;;
                docs)    want_docs=1 ;;
                inert)   ;;
                all)     want_backend=1; want_web=1; want_bicep=1; want_docs=1
                         SCOPE_NOTE="escalated to every area by: $p" ;;
            esac
        done
        want_secrets=1
        [[ -n "$SCOPE_NOTE" ]] || SCOPE_NOTE="${#_paths[@]} changed area(s)"
    fi
fi

# ── Lane machinery ──────────────────────────────────────────────────────────
LOGDIR="$(mktemp -d)"
trap 'rm -rf "$LOGDIR"' EXIT
declare -a LANE_NAMES=()

# Runs name/command pairs in sequence, stopping the lane at the first failure
# (a failed build makes its dependent test phases meaningless noise). Emits a
# machine-readable marker per phase for the summary table.
lane_body() {
    local rc=0 name cmd start end
    while (( $# )); do
        name="$1"; cmd="$2"; shift 2
        echo "── ${name} ──────────────────────────────────────────"
        start=$(date +%s)
        if bash -c "$cmd"; then
            end=$(date +%s)
            echo "@@PHASE ok $((end - start)) ${name}"
        else
            end=$(date +%s)
            echo "@@PHASE fail $((end - start)) ${name}"
            rc=1
            break
        fi
    done
    return $rc
}

start_lane() {
    local lane="$1"; shift
    LANE_NAMES+=("$lane")
    ( lane_body "$@"; echo $? > "$LOGDIR/${lane}.rc" ) >"$LOGDIR/${lane}.log" 2>&1 &
}

echo "verify.sh  mode=${MODE}  config=${CONFIG}"
echo "scope: ${SCOPE_NOTE}"
printf 'gates:'
[[ $want_backend == 1 ]] && printf ' backend'
[[ $want_web     == 1 ]] && printf ' web'
[[ $want_bicep   == 1 ]] && printf ' bicep'
[[ $want_secrets == 1 ]] && printf ' secrets'
[[ $want_docs    == 1 ]] && printf ' docs'
[[ $want_backend == 0 && $want_web == 0 && $want_bicep == 0 && $want_secrets == 0 && $want_docs == 0 ]] && printf ' (none)'
echo
[[ $SLOW_TAIL == 1 ]] && echo "slow tail: backend E2E + web E2E + web perf + Slow-trait tests included"
echo

if [[ $EXPLAIN_ONLY == 1 ]]; then
    exit 0
fi

START_ALL=$(date +%s)

# Lane 1 — backend. Serial within itself: every phase writes or reads bin/obj.
if [[ $want_backend == 1 ]]; then
    backend_phases=(
        "backend build"      "dotnet build ArnBulletinGenerator.slnx -c ${CONFIG}"
        "backend unit tests" "dotnet test ArnBulletinGenerator.slnx -c ${CONFIG} --no-build --filter '${UNIT_FILTER}'"
    )
    if [[ $SLOW_TAIL == 1 ]]; then
        backend_phases+=("backend E2E" "ARN_E2E_TEST_CONFIG=${CONFIG} bash scripts/e2e-backend.sh")
    fi
    start_lane backend "${backend_phases[@]}"
fi

# Lane 2 — lint + generated-doc freshness. `npm run lint` is eslint (JS/TS/React)
# followed by the oxlint-tailwindcss design-system gate (web/.oxlintrc.json) —
# the same command CI's "Frontend lint, test, build" job runs. The inventory
# check fails when web/docs/UI-INVENTORY.md no longer matches src/components/,
# which is the only thing keeping a GENERATED doc honest. Both are read-only, so
# the lane needs no ordering against the web build.
if [[ $want_web == 1 ]]; then
    start_lane weblint \
        "web lint" "cd web && npm run lint" \
        "web ui inventory" "cd web && npm run ui:inventory:check"
fi

# Lane 3 — web build chain. Serial within itself: tsc -b shares .tsbuildinfo,
# and `perf` runs its own vite build (build:mock).
if [[ $want_web == 1 ]]; then
    web_phases=(
        "web typecheck"  "cd web && npx tsc -b"
        "web unit tests" "cd web && npm run test"
        "web build"      "cd web && npm run build"
    )
    # Browser phases are deliberately NOT appended here — see the second wave below.
    start_lane web "${web_phases[@]}"
fi

# Lane 4 — bicep.
if [[ $want_bicep == 1 ]]; then
    if command -v az >/dev/null 2>&1; then
        start_lane bicep "bicep lint" "az bicep build --file deployment/main.bicep --stdout >/dev/null"
    else
        echo "• skipping bicep lint (az not installed)"
    fi
fi

# Lane 5 — secret scan. Mirrors CI exactly (azure-pipelines.yml Secret scan):
# `gitleaks dir` on a CLEAN checkout with the project config. Neither
# alternative matches CI locally: `detect` scans full HISTORY without the
# config (false-positives on long-gone fixture lines), and `dir .` scans
# GITIGNORED local artifacts (job-diagnostics/ SAS payloads) CI never sees.
# Export the tracked tree and scan that.
if [[ $want_secrets == 1 ]]; then
    if command -v gitleaks >/dev/null 2>&1; then
        start_lane secrets "gitleaks" \
            "GLTMP=\$(mktemp -d) && trap 'rm -rf \"\$GLTMP\"' EXIT; git archive HEAD | tar -x -C \"\$GLTMP\" && gitleaks dir \"\$GLTMP\" -c .gitleaks.toml --no-banner --redact --exit-code 1"
    else
        echo "• skipping gitleaks (not installed)"
    fi
fi

# Lane 6 — documentation. Two gates the repository documented as automatic and
# then never ran anywhere routine:
#
#   docs.py check       frontmatter completeness and generated-index freshness.
#                       Required by the repo's own contributor instructions, but
#                       enforced only by whoever remembered.
#   build-docs-site.py  the eleven-class language-contract leak guard for the
#                       ARN-facing documentation site. The 2026-07-28 decision
#                       says the contract is "enforced by the build rather than
#                       by discipline" — but its only caller was the DocsSite
#                       deployment job, behind enableDeploy=true AND a
#                       variable-group deployDocsSite=true. So a docs-only push
#                       cost a secret scan and nothing else, and by 2026-08-03
#                       six leaks (poller x3, two risk identifiers, one
#                       organisation name) had accumulated on published pages.
#
# Both are read-mostly and share no state with the other lanes. The site build
# regenerates the gitignored docs-site/src/content/docs tree, exactly as the
# deploy job does. Serial within the lane: a frontmatter failure makes the leak
# report noise, so stop at the first one.
if [[ $want_docs == 1 ]]; then
    if command -v python3 >/dev/null 2>&1; then
        start_lane docs \
            "docs harness"    "./scripts/docs.py check" \
            "docs leak guard" "./scripts/build-docs-site.py"
    else
        echo "• skipping docs gates (python3 not installed)"
    fi
fi

if [[ ${#LANE_NAMES[@]} -eq 0 && ! ( $SLOW_TAIL == 1 && $want_web == 1 ) ]]; then
    echo "✓ nothing to verify"
    exit 0
fi

if [[ ${#LANE_NAMES[@]} -gt 0 ]]; then
    echo "running ${#LANE_NAMES[@]} lane(s) in parallel: ${LANE_NAMES[*]}"
    wait
fi

# ── Second wave — browser phases, alone ─────────────────────────────────────
# Playwright E2E and the perf budget each drive real Chromium instances, so they are bound by
# MEMORY, not CPU. CI runs them on their own agent; locally every lane shares one box, and run
# beside the backend lanes (dotnet test plus an Azurite-backed Functions host) they lost. The
# failures looked like flakes but were not assertions: "Page crashed" is browser OOM, and the
# 60s timeouts that followed were CPU starvation. Measured on a 16-core/30GB box on 2026-08-03 —
# the suite passed 39/39 alone and failed 8 specs beside the other lanes.
#
# So they run after the first wave drains. Coverage is identical, which is what the 2026-07-29
# CI-mirror incident was about; only local wall time changes, and a serial minute beats a false
# red. web/playwright.config.ts additionally sizes its own worker count from MemAvailable, so
# this wave sees the whole machine's headroom rather than a fraction of it.
if [[ $SLOW_TAIL == 1 && $want_web == 1 ]]; then
    browser_phases=(
        "web e2e"          "cd web && npm run e2e"
        "web perf budget"  "cd web && npm run perf"
    )
    start_lane browser "${browser_phases[@]}"
    echo "running browser lane alone: web e2e + web perf budget"
    wait
fi

END_ALL=$(date +%s)

# ── Report ──────────────────────────────────────────────────────────────────
# Full output only for lanes that failed; a timing table for everything. The
# old script printed every phase's full output unconditionally, which buried
# the one failure that mattered.
FAILED=()
echo ""
echo "═════════════════════════════════════════════════════════"
printf '%-22s %-6s %s\n' "PHASE" "RESULT" "TIME"
for lane in "${LANE_NAMES[@]}"; do
    lane_had_marker=0
    # Marker layout is "@@PHASE <status> <secs> <name...>", so the final read
    # variable absorbs names containing spaces.
    while read -r status secs name; do
        lane_had_marker=1
        if [[ "$status" == "ok" ]]; then
            printf '%-22s %-6s %ss\n' "$name" "✓" "$secs"
        else
            printf '%-22s %-6s %ss\n' "$name" "✗" "$secs"
            FAILED+=("$name")
        fi
    done < <(sed -n 's/^@@PHASE //p' "$LOGDIR/${lane}.log" 2>/dev/null)
    # A lane that died before completing any phase still has to be reported.
    rc="$(cat "$LOGDIR/${lane}.rc" 2>/dev/null || echo 1)"
    if [[ "$rc" != "0" && $lane_had_marker == 0 ]]; then
        printf '%-22s %-6s %s\n' "${lane} lane" "✗" "no phase completed"
        FAILED+=("${lane} lane")
    fi
done

echo "─────────────────────────────────────────────────────────"
echo "wall time: $((END_ALL - START_ALL))s  (lanes: ${LANE_NAMES[*]})"

if [[ ${#FAILED[@]} -eq 0 ]]; then
    echo "✓ all gates passed (${MODE})"
    exit 0
fi

for lane in "${LANE_NAMES[@]}"; do
    rc="$(cat "$LOGDIR/${lane}.rc" 2>/dev/null || echo 1)"
    [[ "$rc" == "0" ]] && continue
    echo ""
    echo "═══ output: ${lane} lane ═════════════════════════════════"
    command grep -v '^@@PHASE ' "$LOGDIR/${lane}.log"
done

echo ""
echo "✗ ${#FAILED[@]} gate(s) failed: ${FAILED[*]}"
exit 1
