#!/usr/bin/env python3
"""Refresh the committed snapshot of the deployed generation pipeline's configuration.

WHY THIS EXISTS (2026-08-23)
----------------------------
Local harnesses (the fallback replay corpus, the scenario matrix, the live evals) exist to answer
"what would production do?". They can only answer it if they run production's configuration, and the
test config's defaults are deliberately not production's. Four harnesses were found running the
legacy raw-model draft path with on-disk prompts and reporting it as deployed behaviour.

Hand-listing the settings in C# fixed those four and would rot the moment someone changed an app
setting. So the settings are snapshotted from the live Function App into a committed JSON file that
`TestConfigurationHelper.DeployedPipeline()` reads, and this script refreshes it.

WHAT IS EXCLUDED, AND WHY
-------------------------
* Secrets (`*ApiKey*`, `*Secret*`, `*ConnectionString*`) - never committed. Credentials come from
  local.settings.json or environment variables, exactly as they do today.
* `Zetta__*` - playout delivery. A local harness must never be one config slip away from writing to
  the live station share, so the snapshot cannot carry the transport, the drop account or the market
  codes. Harnesses set `Providers:OutputProvider=Console`.
* `Storage__*`, `AzureWebJobs*`, `APPLICATIONINSIGHTS*`, `WEBSITE_*`, `FUNCTIONS_*` - host and
  infrastructure wiring with no bearing on what a bulletin says.

USAGE
-----
    python3 scripts/refresh-deployed-pipeline-snapshot.py            # dev (what replay targets)
    python3 scripts/refresh-deployed-pipeline-snapshot.py --env test
    python3 scripts/refresh-deployed-pipeline-snapshot.py --check    # non-zero on drift, no write
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

SNAPSHOT = Path("test/corpus/deployed-pipeline.json")

APPS = {
    "dev": ("IBP-AUE-DEV-FNA-APP01", "IBP-AUE-DEV-RSG-APP01"),
    "test": ("IBP-AUE-TST-FNA-APP01", "IBP-AUE-TST-RSG-APP01"),
    "prod": ("IBP-AUE-PRD-FNA-APP01", "IBP-AUE-PRD-RSG-APP01"),
}

# Sections that decide what a bulletin says or how long it runs.
INCLUDED_PREFIXES = (
    "Broadcast__",
    "AiSettings__",
    "SpeechDuration__",
    "Weather__",
    "Fuel__",
    "ContentSelection__",
    "Prompts__",
)

# Never committed, never needed by a harness.
EXCLUDED_PREFIXES = ("Zetta__", "Storage__")
SECRET_MARKERS = ("apikey", "secret", "connectionstring", "password", "token")


def fetch(env: str) -> dict[str, str]:
    name, group = APPS[env]
    result = subprocess.run(
        ["az", "functionapp", "config", "appsettings", "list",
         "-n", name, "-g", group, "--query", "[].{n:name,v:value}", "-o", "json"],
        capture_output=True, text=True, timeout=300,
    )
    if result.returncode != 0:
        sys.exit(f"az failed for {env}: {result.stderr.strip()[:300]}")
    return {row["n"]: row["v"] for row in json.loads(result.stdout)}


def relevant(settings: dict[str, str]) -> dict[str, str]:
    kept: dict[str, str] = {}
    for key, value in sorted(settings.items()):
        if not key.startswith(INCLUDED_PREFIXES):
            continue
        if key.startswith(EXCLUDED_PREFIXES):
            continue
        if any(marker in key.lower() for marker in SECRET_MARKERS):
            continue
        # An empty deployed value means "unset here"; recording it would override an appsettings
        # default with blank and change behaviour the deployed app does not have.
        if value is None or value == "":
            continue
        kept[key] = value
    return kept


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--env", default="dev", choices=sorted(APPS))
    parser.add_argument("--check", action="store_true",
                        help="compare only; exit non-zero if the snapshot is stale")
    args = parser.parse_args()

    live = relevant(fetch(args.env))
    payload = {
        "_comment": (
            "Generated by scripts/refresh-deployed-pipeline-snapshot.py - do not hand-edit. "
            "This is the deployed generation configuration that local harnesses must run so their "
            "reports describe production. Secrets, Zetta playout and host wiring are excluded."
        ),
        "environment": args.env,
        "settings": live,
    }
    rendered = json.dumps(payload, indent=2, sort_keys=False) + "\n"

    if args.check:
        if not SNAPSHOT.exists():
            print(f"MISSING {SNAPSHOT}")
            return 1
        current = json.loads(SNAPSHOT.read_text()).get("settings", {})
        added = {k: v for k, v in live.items() if k not in current}
        removed = {k: v for k, v in current.items() if k not in live}
        changed = {k: (current[k], live[k]) for k in live if k in current and current[k] != live[k]}
        if not (added or removed or changed):
            print(f"OK snapshot matches {args.env} ({len(live)} settings)")
            return 0
        for key, value in added.items():
            print(f"ADDED    {key} = {value}")
        for key in removed:
            print(f"REMOVED  {key}")
        for key, (was, now) in changed.items():
            print(f"CHANGED  {key}: {was} -> {now}")
        return 1

    SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT.write_text(rendered)
    print(f"wrote {SNAPSHOT} from {args.env} ({len(live)} settings)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
